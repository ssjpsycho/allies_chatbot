import asyncio
import hashlib
import sys

import httpx
import pytest

from allies_bot import audit
from allies_bot.audit import (
    AuditSettings,
    PageSnapshot,
    WikiSnapshot,
    attribute_candidates,
    audit_snapshot,
    extract_records,
    parse_source,
    progression_entries,
    render_report,
)


def page(html: str, **overrides) -> PageSnapshot:
    return PageSnapshot.model_validate({
        "id": 46, "title": "Judgment Family",
        "url": "https://wiki.test/books/rules/page/judgment",
        "book": "Character Creation & Advancement", "chapter": "Spiritual Effects",
        "updated_at": "2026-11-12", "html": html,
        "content_sha256": hashlib.sha256(html.encode()).hexdigest(), **overrides,
    })


def snapshot(*pages: PageSnapshot) -> WikiSnapshot:
    return WikiSnapshot(captured_at="2026-11-12", base_url="https://wiki.test", pages=list(pages))


FAMILY_HTML = """
<table id="progression"><tr><td>Progression</td><td>Tier:1</td><td>Tier:2</td></tr>
<tr><td>1</td><td><p>Gavel of Judgment</p></td>
<td><p>Sanctified</p><p>Gavel of Judgment</p></td></tr></table>
<h4 id="gavel">Gavel of Judgment</h4>
<p id="damage">Gavel of Judgment damages Resolve instead of Endurance.</p>
<p>The damage is Resistible using Resolve. It lasts 1 Turn.</p>
<h4 id="other">Unrelated notes</h4><p>Not part of Gavel.</p>
"""


def test_source_parser_keeps_cells_headings_and_anchors() -> None:
    _, blocks = parse_source(page(FAMILY_HTML))
    assert blocks[0].rows[1][2].text == "Sanctified Gavel of Judgment"
    assert blocks[1].source_url.endswith("#gavel")
    assert blocks[2].source_url.endswith("#damage")
    assert blocks[3].source_url.endswith("#gavel")  # not the previous paragraph's anchor
    assert blocks[2].heading_path == ["Gavel of Judgment"]
    entries = progression_entries(blocks)
    assert [(e.tier, e.position, e.row, e.column) for e in entries] == [(1, 1, 1, 1), (2, 1, 1, 2)]


def test_record_has_own_rules_and_all_referenced_evidence() -> None:
    p = page(FAMILY_HTML)
    _, blocks = parse_source(p)
    record = next(r for r in extract_records(p, blocks) if r.name == "Gavel of Judgment")
    assert record.category == "spiritual_effect"
    assert record.fields["eligibility_mentions"].status == "unknown"
    assert record.fields["eligibility_mentions"].quotes == []
    assert record.fields["damage_mentions"].quotes == [
        "Gavel of Judgment damages Resolve instead of Endurance.",
        "The damage is Resistible using Resolve.",
    ]
    assert not any("Unrelated" in e.text for e in record.evidence)
    evidence_ids = {e.id for e in record.evidence}
    assert all(e.evidence_id in evidence_ids for e in record.progression)
    assert all(set(f.evidence_ids) <= evidence_ids for f in record.fields.values())
    assert any("Tier variants" in flag for flag in record.review_flags)
    assert record.review_status == "needs_review"


def test_classification_uses_hierarchy_not_family_name() -> None:
    p = page(FAMILY_HTML, title="Flame Family", chapter="Songs")
    _, blocks = parse_source(p)
    assert extract_records(p, blocks)[0].category == "song"
    evil = p.model_copy(update={"book": "Catalogue of Evil"})
    assert extract_records(evil, blocks) == []


@pytest.mark.parametrize("cell", ['rowspan="2"', 'colspan="2"'])
def test_merged_progression_is_flagged_not_guessed(cell: str) -> None:
    p = page(FAMILY_HTML.replace("<td>1</td>", f"<td {cell}>1</td>"))
    _, blocks = parse_source(p)
    assert progression_entries(blocks) == []
    result, _ = audit_snapshot(snapshot(p))
    assert {"merged_table_cells", "unparsed_progression"} <= {f.code for f in result.findings}


