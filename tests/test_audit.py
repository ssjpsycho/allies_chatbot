def test_snapshot_capture_only_uses_get(monkeypatch) -> None:
    calls = []

    async def get(_client, path, **kwargs):
        calls.append((path, kwargs))
        payloads = {
            "/api/pages": {"total": 1, "data": [{"id": 46}]},
            "/api/pages/46": {
                "id": 46, "name": "Judgment Family", "book_id": 1, "chapter_id": 2,
                "slug": "judgment", "html": FAMILY_HTML,
            },
            "/api/books/1": {"name": "Character Creation & Advancement", "slug": "rules"},
            "/api/chapters/2": {"name": "Spiritual Effects"},
        }
        return httpx.Response(200, json=payloads[path], request=httpx.Request("GET", "https://wiki.test"))

    monkeypatch.setattr(audit, "get_bookstack", get)
    result = asyncio.run(audit.capture_wiki(AuditSettings(
        bookstack_base_url="https://wiki.test", bookstack_token="test",
    )))
    assert len(calls) == 4
    assert result.pages[0].html == FAMILY_HTML
    assert result.pages[0].chapter == "Spiritual Effects"
    assert "test" not in result.model_dump_json().replace("wiki.test", "")


def test_offline_cli_needs_no_services_and_refuses_overwrite(tmp_path, monkeypatch) -> None:
    source = tmp_path / "input.json"
    source.write_text(snapshot(page(FAMILY_HTML)).model_dump_json(), encoding="utf-8")
    output = tmp_path / "output"
    monkeypatch.setattr(sys, "argv", [
        "audit", "--snapshot", str(source), "--output", str(output),
    ])

    async def forbidden(*_args):
        raise AssertionError("Offline audit must never contact BookStack.")

    monkeypatch.setattr(audit, "capture_wiki", forbidden)
    asyncio.run(audit.main())
    assert {p.name for p in output.iterdir()} == {
        "snapshot.json", "audit.json", "records.json", "report.html",
    }
    with pytest.raises(SystemExit) as exc:
        asyncio.run(audit.main())
    assert exc.value.code == 2


