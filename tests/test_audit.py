def test_snapshot_rejects_duplicate_ids_and_altered_content() -> None:
    p = page(FAMILY_HTML)
    with pytest.raises(ValueError, match="unique"):
        snapshot(p, p)
    with pytest.raises(ValueError, match="hash mismatch"):
        snapshot(p.model_copy(update={"html": "<p>Changed</p>"}))


def test_prose_table_disagreement_is_flagged_with_both_values() -> None:
    p = page(FAMILY_HTML.replace(
        "<h4 id=\"other\">",
        '<p>The Hammer causes Falter:1.</p><table><tr><td>Gavel of Judgment</td>'
        '<td>12 = Falter:2</td></tr></table><h4 id="other">',
    ))
    result, _ = audit_snapshot(snapshot(p))
    finding = next(f for f in result.findings if f.code == "potential_rule_mismatch")
    assert "prose ['1']" in finding.detail
    assert "base table ['2']" in finding.detail


def test_visual_heading_between_empty_headings_recovers_description() -> None:
    source = FAMILY_HTML.replace(
        '<h4 id="gavel">Gavel of Judgment</h4>',
        '<h4 id="empty"></h4><p id="visual"><strong>Gavel of Judgment</strong></p><h4></h4>',
    )
    p = page(source)
    result, pilot = audit_snapshot(snapshot(p))
    record = next(r for r in pilot.records if r.name == "Gavel of Judgment")
    assert len(record.progression) == 2
    assert record.source_url.endswith("#visual")
    assert record.evidence[0].heading_basis == "progression_label_after_empty_heading"
    assert record.fields["damage_mentions"].status == "candidate"
    assert any("damages Resolve" in q for q in record.fields["damage_mentions"].quotes)
    assert not any("Unrelated" in e.text for e in record.evidence)
    assert not any(f.code == "unmatched_progression_entry" for f in result.findings)
    assert any(f.code == "recovered_visual_heading" for f in result.findings)
    assert all("" not in e.heading_path for e in record.evidence)


